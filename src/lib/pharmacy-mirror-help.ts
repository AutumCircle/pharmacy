export type MirrorHelpTopic = keyof typeof mirrorHelp;

export function oracleFieldHelpTopic(key: string): MirrorHelpTopic {
  if (key === 'PRODUCT_ID') return 'productId';
  if (key === 'INCOME_ID' || key === 'INCOME_HEAD_ID') return 'receiptId';
  if (key === 'SKLAD_ID') return 'warehouse';
  if (key === 'PRODUCT_COUNT_REZERV') return 'reserve';
  if (key === 'PRODUCT_COUNT_SKLAD') return 'stock';
  if (key === 'INCOME_DATE_OLD') return 'sourceDate';
  if (key === 'INCOME_PRICE_W_NDS') return 'purchase';
  if (key === 'OUTCOME_PRICE_ONE_W_NDS') return 'sale';
  if (key === 'INCOME_SUM_W_NDS') return 'incomeSum';
  return 'raw';
}
