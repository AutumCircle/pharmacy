export function oracleFieldLabel(key: string): string {
  if (labels[key]) return labels[key];
  if (key.startsWith('EXT_')) return `Внешний приход: ${labels[key.slice(4)] || key.slice(4)}`;
  return `Исходное поле ${key}`;
}
export function oracleFieldValue(value: OracleValue | undefined): string {
  if (value === null || value === undefined || value === '') return 'Не заполнено';
  return typeof value === 'boolean' ? (value ? 'Да' : 'Нет') : String(value);
}
